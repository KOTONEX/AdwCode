//! 命令行解析与子命令分发；子命令、参数与提示使用简体中文。

use crate::错误::{工具错误, 结果};

const 帮助文本: &str = "\
AdwCode 构建与打包工具

用法：adwcode <子命令> [参数]

子命令：
  主题                 生成主题并同步 package.json（--监视 添加调试标记）
  校验                 校验已生成的主题、产品图标与颜色键
  检查样式             对照已安装的 VS Code 检查自定义 CSS（--样式表 路径）
  打包                 生成 VSIX（--变更日志 路径 供无 Git 副本使用）
  变更日志             生成 CHANGELOG.md
  发布说明             生成发布说明（--标签 vX.Y.Z）
  发布策略             判断候选与市场发布权限（--引用 refs/...，--输出 路径）
  发布上传             上传 Release 或发布市场（--引用 refs/tags/v<版本>，--目标 Release/市场，--预演）
  验证设置             校验清单默认设置、命令与工作区能力
  更新默认数据         刷新随附的 VS Code 数据与颜色键表
  性能基准             运行离线性能基准
  工作台基准           在独立窗口运行界面基准（--浏览器工具 路径）
  生成自有字形         生成自有产品图标字体
  生成导入字形         生成导入产品图标字体与预览
  检查                 运行静态检查、类型检查与离线测试
  格式化               格式化全部源码
  类型检查             检查 Rust 与扩展 JavaScript 类型
  帮助                 显示本说明
";

/// 执行命令行；返回 `Ok(())` 表示成功。
pub fn 执行(参数: &[String]) -> 结果<()> {
    let Some((子命令, 其余)) = 参数.split_first() else {
        print!("{帮助文本}");
        return Ok(());
    };
    if matches!(
        子命令.as_str(),
        "帮助" | "--帮助" | "-h" | "校验" | "检查" | "格式化" | "类型检查" | "验证设置"
    ) && let Some(参数) = 其余.first()
    {
        return Err(工具错误::新(format!("{子命令} 不接受参数：{参数}")));
    }
    match 子命令.as_str() {
        "帮助" | "--帮助" | "-h" => {
            print!("{帮助文本}");
            Ok(())
        }
        "主题" => crate::主题生成::生成入口(&crate::仓库::根目录()?, 其余),
        "校验" => crate::主题生成::校验入口(&crate::仓库::根目录()?),
        "变更日志" => crate::变更日志::入口(&crate::仓库::根目录()?, false, 其余),
        "发布说明" => crate::变更日志::入口(&crate::仓库::根目录()?, true, 其余),
        "发布策略" => crate::发布策略::入口(&crate::仓库::根目录()?, 其余),
        "发布上传" => crate::发布上传::入口(&crate::仓库::根目录()?, 其余),
        "验证设置" => crate::验证设置::验证设置(&crate::仓库::根目录()?),
        "打包" => crate::打包::入口(&crate::仓库::根目录()?, 其余),
        "检查样式" => crate::检查样式::入口(&crate::仓库::根目录()?, 其余),
        "更新默认数据" => crate::更新默认数据::入口(&crate::仓库::根目录()?, 其余),
        "生成自有字形" => crate::图标生成::自有入口(&crate::仓库::根目录()?, 其余),
        "生成导入字形" => crate::图标生成::导入入口(&crate::仓库::根目录()?, 其余),
        "性能基准" => crate::性能基准::入口(&crate::仓库::根目录()?, 其余),
        "工作台基准" => crate::工作台基准::入口(&crate::仓库::根目录()?, 其余),
        "检查" => crate::检查::检查(&crate::仓库::根目录()?),
        "格式化" => crate::检查::格式化(&crate::仓库::根目录()?),
        "类型检查" => crate::检查::类型检查(&crate::仓库::根目录()?),
        其他 => Err(工具错误::新(format!(
            "未知子命令：{其他}；运行 adwcode 帮助 查看用法"
        ))),
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 无参数时打印帮助() {
        assert!(执行(&[]).is_ok());
    }

    #[test]
    fn 未知子命令报错() {
        let 参数 = vec!["不存在".to_string()];
        let 错误 = 执行(&参数).unwrap_err();
        assert!(错误.消息.contains("未知子命令：不存在"));
    }

    #[test]
    fn 无参数命令拒绝多余输入() {
        for 命令 in ["帮助", "校验", "检查", "格式化", "类型检查", "验证设置"] {
            assert!(执行(&[命令.to_string(), "--不存在".to_string()]).is_err());
        }
    }
}
